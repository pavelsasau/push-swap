package stack

//SA
func Sa(a []int) { // меняем первые два числа стека A
	if len(a) < 2 { // если чисел меньше двух
		return // ничего не делаем
	}

	a[0], a[1] = a[1], a[0] // меняем числа местами
}

//SB
func Sb(b []int) { // меняем первые два числа стека B
	if len(b) < 2 { // если чисел меньше двух
		return
	}

	b[0], b[1] = b[1], b[0] // меняем числа местами
}

//SS
func Ss(a []int, b []int) { // меняем первые два числа в обоих стеках
	Sa(a) // выполняем sa
	Sb(b) // выполняем sb
}

//PA
func Pa(a *[]int, b *[]int) { // переносим первое число из B в A
	if len(*b) == 0 { // если B пустой
		return
	}

	num := (*b)[0]                   // берём первое число B
	*b = (*b)[1:]                    // убираем его из B
	*a = append([]int{num}, (*a)...) // добавляем число в начало A
}

//PB
func Pb(a *[]int, b *[]int) { // переносим первое число из A в B
	if len(*a) == 0 { // если A пустой
		return
	}

	num := (*a)[0]                   // берём первое число A
	*a = (*a)[1:]                    // убираем его из A
	*b = append([]int{num}, (*b)...) // добавляем число в начало B
}

//RA
func Ra(a *[]int) { // переносим первое число A в конец
	if len(*a) < 2 { // если чисел меньше двух
		return
	}

	num := (*a)[0]       // запоминаем первое число
	*a = (*a)[1:]        // убираем первое число
	*a = append(*a, num) // добавляем его в конец
}

//RB
func Rb(b *[]int) { // переносим первое число B в конец
	if len(*b) < 2 {
		return
	}

	num := (*b)[0]       // запоминаем первое число
	*b = (*b)[1:]        // убираем первое число
	*b = append(*b, num) // добавляем его в конец
}

//RR
func Rr(a *[]int, b *[]int) { // прокручиваем оба стека
	Ra(a) // первое число A переносим в конец
	Rb(b) // первое число B переносим в конец
}

//RRA
func Rra(a *[]int) { // переносим последнее число A в начало
	if len(*a) < 2 {
		return
	}

	num := (*a)[len(*a)-1]           // берём последнее число
	*a = (*a)[:len(*a)-1]            // убираем последнее число
	*a = append([]int{num}, (*a)...) // добавляем его в начало
}

//RRB
func Rrb(b *[]int) { // переносим последнее число B в начало
	if len(*b) < 2 {
		return
	}

	num := (*b)[len(*b)-1]           // берём последнее число
	*b = (*b)[:len(*b)-1]            // убираем последнее число
	*b = append([]int{num}, (*b)...) // добавляем его в начало
}

//RRR
func Rrr(a *[]int, b *[]int) { // обратная прокрутка обоих стеков
	Rra(a) // последнее число A переносим в начало
	Rrb(b) // последнее число B переносим в начало
}
